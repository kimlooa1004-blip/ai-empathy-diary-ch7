/** 띄어쓰기를 지우고 본다. "죽고 싶다"와 "죽고싶다"를 같이 잡기 위함이다. */
function 띄어쓰기지우기(글: string): string {
  return 글.replace(/\s+/g, "");
}

const 위기낱말 = [
  "자살",
  "죽고싶",
  "죽어버리",
  "죽을래",
  "자해",
  "극단적선택",
  "목숨을끊",
  "사라지고싶",
  "없어지고싶",
  "그만살고싶",
  "다그만두고싶",
  "살기싫",
  "살고싶지않",
  "뛰어내리",
  "유서",
].map(띄어쓰기지우기);

/** 글에 위기 표현이 보이면 참을 돌려준다. */
export function 위기낱말있나(글: string): boolean {
  const 붙인글 = 띄어쓰기지우기(글);
  return 위기낱말.some((낱말) => 붙인글.includes(낱말));
}

